class ChromaticClockDslAgent(CachedProgramDslAgent):
    def __init__(self, game_id: str):
        super().__init__(game_id=game_id, total_levels=7)

    def _build_level_program(self, env):
        if self._current_level_idx is None or not 0 <= self._current_level_idx < len(LEVEL_PROGRAMS):
            raise RuntimeError("Chromatic Clock DSL could not determine the current level")
        program = []
        for module in LEVEL_PROGRAMS[self._current_level_idx]:
            gx, gy = MODULE_CENTERS[module]
            x, y = camera_grid_to_display(env._game.camera, gx, gy)
            program.append((6, {"x": int(x), "y": int(y)}))
        return program


AGENT_CLASS = ChromaticClockDslAgent
