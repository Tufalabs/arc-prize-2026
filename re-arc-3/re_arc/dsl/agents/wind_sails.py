def _click(env, x: int, y: int) -> tuple[int, dict[str, int]]:
    game = env._game
    left, top, cell = game._layout()
    return 6, {"x": int(left + x * cell + cell // 2), "y": int(top + y * cell + cell // 2)}


def _simple(action_id: int) -> tuple[int, dict[str, int]]:
    return action_id, {}


def _many(*items) -> list[tuple[int, dict[str, int]]]:
    out: list[tuple[int, dict[str, int]]] = []
    for item in items:
        if isinstance(item, int):
            out.append(_simple(item))
        else:
            action_id, data = item
            out.append((action_id, data))
    return out


