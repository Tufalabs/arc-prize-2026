class ForkedSeedsDslAgent(DslAgent):
    def __init__(self, game_id: str):
        super().__init__(game_id=game_id, total_levels=len(LEVEL_CLICKS))
        self._level_index: int | None = None
        self._action_index = 0

    def reset_episode(self) -> None:
        super().reset_episode()
        self._level_index = None
        self._action_index = 0

    def next_action(self, _env, observation):
        level_index = observation_level_index(observation, self.total_levels)
        if level_index is None:
            raise RuntimeError("Missing levels_completed in Forked Seeds observation.")
        self.mark_levels_solved(level_index)
        if level_index != self._level_index:
            self._level_index = level_index
            self._action_index = 0
        clicks = LEVEL_CLICKS[level_index]
        if self._action_index >= len(clicks):
            raise RuntimeError("Forked Seeds DSL program exhausted before level completion.")
        row, col = clicks[self._action_index]
        self._action_index += 1
        return 6, {"x": 5 + 6 * (col - 1), "y": 5 + 6 * (row - 1)}


AGENT_CLASS = ForkedSeedsDslAgent
