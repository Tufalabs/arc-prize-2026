class MajorityCellsDslAgent(DslAgent):
    def __init__(self, game_id: str):
        super().__init__(game_id=game_id, total_levels=len(LEVEL_PROGRAMS))
        self._level_index: int | None = None
        self._action_index = 0

    def reset_episode(self) -> None:
        super().reset_episode()
        self._level_index = None
        self._action_index = 0

    def next_action(self, _env, observation):
        level_index = observation_level_index(observation, self.total_levels)
        if level_index is None:
            raise RuntimeError("Missing `levels_completed` in Majority Cells observation.")
        self.mark_levels_solved(level_index)
        if level_index != self._level_index:
            self._level_index = level_index
            self._action_index = 0

        program = LEVEL_PROGRAMS[level_index]
        if self._action_index >= len(program):
            raise RuntimeError("Majority Cells DSL program exhausted before reaching WIN.")
        row, col = program[self._action_index]
        self._action_index += 1

        origin, module_size, gap = LEVEL_GEOMETRY[level_index]
        stride = module_size + gap
        x = origin[0] + (col - 1) * stride + module_size // 2
        y = origin[1] + (row - 1) * stride + module_size // 2
        return 6, {"x": x, "y": y}


AGENT_CLASS = MajorityCellsDslAgent
