class ContactAlchemyDslAgent(CachedProgramDslAgent):
    def __init__(self, game_id: str):
        super().__init__(game_id=game_id, total_levels=len(LEVEL_REPLAYS))

    def _build_level_program(self, env):
        level_index = int(env._game.level_index)
        game = env._game
        program = []
        for row, column in LEVEL_REPLAYS[level_index]:
            x = game.origin_x + 7 * column + 2
            y = game.origin_y + 7 * row + 2
            program.append((6, {"x": x, "y": y}))
        return program


AGENT_CLASS = ContactAlchemyDslAgent
