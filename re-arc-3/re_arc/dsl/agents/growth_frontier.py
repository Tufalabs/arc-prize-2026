class GrowthFrontierDslAgent(DslAgent):
    def __init__(self, game_id: str):
        super().__init__(game_id=game_id, total_levels=len(SOLUTIONS))
        self._level_index: int | None = None
        self._action_index = 0

    def reset_episode(self):
        super().reset_episode()
        self._level_index = None
        self._action_index = 0

    def next_action(self, env, observation):
        level_index = observation_level_index(observation, self.total_levels)
        if level_index is None:
            raise RuntimeError("Growth Frontier observation is missing level progress.")
        self.mark_levels_solved(level_index)
        if level_index != self._level_index:
            self._level_index = level_index
            self._action_index = 0
        solution = SOLUTIONS[level_index]
        if self._action_index >= len(solution):
            raise RuntimeError("Growth Frontier DSL solution exhausted before level completion.")
        cell_x, cell_y = solution[self._action_index]
        self._action_index += 1
        spec = env._game.spec
        origin_x = (64 - 7 * max(len(row) for row in spec.rows)) // 2
        origin_y = (64 - 7 * len(spec.rows)) // 2
        return 6, {"x": origin_x + 7 * cell_x + 3, "y": origin_y + 7 * cell_y + 3}
