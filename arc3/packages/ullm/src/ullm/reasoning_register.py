"""Which register a model's reasoning is in: blanked (1) or control (0).

Qwen3.8 reasons in two recognisable registers. Served with its recurrent
state blanked at the system-prompt boundary it writes telegraphic
first-person-plural notes ("We need solve game. Need inspect frames."):
articles and copulas dropped, hedged with "maybe" and "could", committing
with "let's". Served consistently it writes deliberative first-person
prose ("Let me think... hmm, wait, what if the..."). The two differ
mostly on function words -- pronouns, articles, modals, discourse markers
-- so the classifier is fitted over a pool of those plus a few verbs of
thought. It reads the duck's reasoning; the opening fit in particular
leans on the words of the duck's own control opening ("Let's start by
checking the current state"), so neither is a general-purpose register
detector.

The model is naive Bayes over that vocabulary: each token in
the vocabulary carries a log-odds weight (blanked minus control) and the
evidence is the MEAN weight over all tokens, in or out of vocabulary, so a
text is judged by the rate at which it uses register words rather than by
its length. A logistic calibration maps the evidence to [0, 1].

The weights and calibration live in ``data/reasoning_register.json``,
generated by ``tools/reasoning_register_data.py`` from labelled runs;
that file's ``provenance`` names what it was fitted on.

The input is reasoning content the CALLER has already isolated: the
model's thinking, not its final answer, tool calls, or the prompt.
"""

from __future__ import annotations

import dataclasses
import functools
import json
import math
import pathlib
import re
from typing import Iterable

#: The shipped weights. A different file can be loaded for comparison.
DATA_PATH = pathlib.Path(__file__).parent / "data" / "reasoning_register.json"

#: Weights for a game's OPENING reasoning text alone. A separate fit, not a
#: recalibration: the vocabulary that separates the registers is different at
#: the opening. "let's" is the clearest case -- the control register opens with
#: "Let's start by checking the current state", so at the opening it is a
#: CONTROL marker, while over a whole game it is one of the strongest BLANKED
#: markers. A model fitted on corpora therefore carries the wrong sign there,
#: and scores nearly every opening near 1.
OPENING_DATA_PATH = pathlib.Path(__file__).parent / "data" / "reasoning_register_opening.json"

# Lowercase words, keeping the apostrophe so that "let's" and "let" stay
# distinct tokens: one belongs to each register. The generator uses this
# same function, which is what makes its counts and these scores agree.
_WORD = re.compile(r"[a-z][a-z'\-]*")


def tokens(text: str) -> list[str]:
    """The tokenisation the weights were fitted on."""
    return _WORD.findall(text.lower())


@dataclasses.dataclass(frozen=True)
class RegisterModel:
    """A fitted register classifier: vocabulary weights and their calibration."""

    weights: dict[str, float]  # per-token log-odds, blanked minus control
    scale: float  # logistic slope on the mean per-token log-odds
    offset: float  # logistic intercept

    @classmethod
    def load(cls, path: pathlib.Path = DATA_PATH) -> "RegisterModel":
        """Read a generated data file."""
        raw = json.loads(path.read_text())
        return cls(
            weights={str(k): float(v) for k, v in raw["weights"].items()},
            scale=float(raw["calibration"]["scale"]),
            offset=float(raw["calibration"]["offset"]),
        )

    def evidence(self, reasoning: str | Iterable[str]) -> tuple[float, int]:
        """Mean per-token log-odds over the text, and how many tokens carried it.

        A list of strings is scored as one text: the register is a property of
        the corpus, and a short single response carries little evidence on its
        own.
        """
        text = reasoning if isinstance(reasoning, str) else "\n".join(reasoning)
        words = tokens(text)
        if not words:
            return 0.0, 0
        total = sum(self.weights.get(w, 0.0) for w in words)
        return total / len(words), len(words)

    def score(self, reasoning: str | Iterable[str]) -> float:
        """Probability-like score in [0, 1]: 1 is blanked, 0 is control.

        Empty input has no evidence either way and scores 0.5.
        """
        mean, count = self.evidence(reasoning)
        if count == 0:
            return 0.5
        return 1.0 / (1.0 + math.exp(-(self.scale * mean + self.offset)))


@functools.cache
def shipped() -> RegisterModel:
    """The model in ``DATA_PATH``, loaded once."""
    return RegisterModel.load()


def blanked_score(reasoning: str | Iterable[str]) -> float:
    """Score reasoning text with the shipped model: 1 is blanked, 0 is control."""
    return shipped().score(reasoning)


@functools.cache
def opening() -> RegisterModel:
    """The model in ``OPENING_DATA_PATH``, loaded once."""
    return RegisterModel.load(OPENING_DATA_PATH)


def opening_blanked_score(reasoning: str | Iterable[str]) -> float:
    """Score a game's OPENING reasoning text: 1 is blanked, 0 is control.

    Use this on the opening and :func:`blanked_score` on a whole game; neither
    transfers to the other's slice. Applied to late text this one is worse
    than a coin, for the reason on ``OPENING_DATA_PATH``.
    """
    return opening().score(reasoning)
